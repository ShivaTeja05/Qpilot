def ledger(table=None, design="toy", *, refs=REFS, doc=None) -> EvidenceLedger:
    """The ledger of a toy study; ``design=None`` is the legacy (no design) analysis."""
    table = toy_table() if table is None else table
    design = toy_design() if design == "toy" else design
    return evidence_for(table, toy_model(table, design, refs=refs), design, doc)


def fact(led: EvidenceLedger, item: str, name: str):
    return led.facts[f"f_ev_{item}_{name}"].value


def facts_of(led: EvidenceLedger, item: str, *names: str) -> tuple:
    return tuple(fact(led, item, name) for name in names)


def code(led: EvidenceLedger, item: str) -> tuple[str, str]:
    entry = led.item(item)
    return entry.status, entry.consequence.code


def no_flags(samples=()) -> RdmlEvidence:
    """A file with five runs naming nothing and samples with no annotation."""
    runs = tuple(RunFlags("exp", f"p{i}", False, False, False) for i in range(len(TARGETS)))
    return RdmlEvidence(runs=runs, samples={s: SampleFlags() for s in samples})


