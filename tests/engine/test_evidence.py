def test_rendered_ledger_passes_the_validator():
    for led in (ledger(), ledger(doc=no_flags(ALL_SAMPLES)), ledger(toy_table(rt_shift=1.5))):
        text = render_evidence(led.facts)
        assert validate(text.tokens, led.facts).ok
        assert "{{" not in text.plain and "{{" not in text.html
