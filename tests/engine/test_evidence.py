def test_items_are_fixed_and_complete():
    led = ledger()
    assert [entry.id for entry in led.items] == list(ITEMS)
    assert len(ITEMS) == 11 and set(ITEM_TITLES) == set(MIQE_ITEMS) == set(ITEMS)
    for entry in led.items:
        assert entry.status in STATUSES
        assert entry.consequence.text == CONSEQUENCES[entry.consequence.code]
        assert entry.miqe == list(MIQE_ITEMS[entry.id])
        assert all(fid.startswith(f"f_ev_{entry.id}_") for fid in entry.facts)
        assert set(TOKEN.findall(entry.consequence.text)) <= set(entry.facts)
        assert set(entry.facts) <= set(led.facts)
    assert sum(led.counts().values()) == len(ITEMS) == led.facts["f_ev_n_items"].value


def test_every_consequence_cites_only_its_own_item():
    for key, text in CONSEQUENCES.items():
        ids = TOKEN.findall(text)
        items = {next(i for i in ITEMS if fid.startswith(f"f_ev_{i}_")) for fid in ids}
        assert len(items) <= 1, key
        assert not re.search(r"\d", TOKEN.sub("", text)), key  # no naked digit in any template


