def _spanning(table: pd.DataFrame, shared: bool) -> pd.DataFrame:
    """T2 measured on a second plate (p9): the A group there, sharing u1a only if ``shared``."""
    moved = table[(table["target"] == "T2") & table["sample"].isin(["u4a", "u4b", "u5a"])].copy()
    moved["run_id"] = "p9"
    keep = table[~((table["target"] == "T2") & table["sample"].isin(["u4a", "u4b", "u5a"]))]
    if shared:
        copy = table[(table["target"] == "T2") & (table["sample"] == "u1a")].copy()
        copy["run_id"], copy["well"] = "p9", "B1"
        moved = pd.concat([moved, copy])
    return pd.concat([keep, moved], ignore_index=True)


