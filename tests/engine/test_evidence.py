def test_the_ledger_never_changes_the_study():
    table = toy_table()
    design = toy_design()
    model = toy_model(table, design)
    before_table = table.copy()
    before_genorm = model.stability.model_dump()
    evidence_for(table, model, design)
    pd.testing.assert_frame_equal(table, before_table)
    assert model.stability.model_dump() == before_genorm
    from qpilot.qpcr.study import StudySettings, study_from_curves

    settings = StudySettings.from_design(design)
    result, _, _ = study_from_curves(table, "cd" * 32, settings)
    assert not any(fid.startswith("f_ev_") for fid in result.facts)
    assert "evidence" not in result.model_dump()


def test_absent_items_never_downgrade_the_grade():
    from qpilot.core.confidence import DOWNGRADING_CHECKS
    from qpilot.qpcr.study import StudySettings, study_from_curves

    table = toy_table()
    design = toy_design(rt_labels=False)
    led = ledger(table, design)
    assert led.item("rt_replicates").status == "absent"
