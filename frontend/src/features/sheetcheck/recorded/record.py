"""Record real JSON for the Sheet check's tests from a running `qpilot app` (never typed in).

The sheets are generated with the engine's own test helpers (``tests/engine/test_sheetcheck.py``),
uploaded to the server as the page uploads them, and checked as the page checks them; what the
server answers is written next to this file. Run from the repository root (the tests package must
be importable) with a server whose store holds the analysed demo study:

    qpilot app --no-open --port 7896 &
    python frontend/src/features/sheetcheck/recorded/record.py --port 7896 --study e300000d4f9a

It writes:

* ``workspaces.json`` -- ``GET /api/workspaces`` (the studies a sheet can be compared with);
* ``clean-upload.json`` -- ``POST /api/sheets`` with the clean synthetic sheet (``clean_sheet``);
* ``clean-guessed.json`` -- ``POST /api/sheets/{id}/check`` ``{}``: the mapping is a guess;
* ``clean-changed.json`` -- the same with one column set by a person (its fold-change column
  taken as "not used"), not confirmed;
* ``clean-confirmed.json`` -- that mapping confirmed (``confirm: true``);
* ``inverted-upload.json``, ``inverted-guessed.json`` -- a sheet whose MYC fold changes are
  ``2^+ΔΔCq`` (the sign inverted), as ``tests/web/test_sheets.py`` builds it;
* ``dates-upload.json``, ``dates-guessed.json`` -- a long sheet whose MARCH1 rows say ``1-Mar``
  (a gene name a spreadsheet turned into a date), as the engine test builds it;
* ``demo-upload.json``, ``demo-study.json`` -- a sheet built from the demo's own Cq values
  (``demo_table``/``demo_clean``), checked against the demo study: its hand-overs;
* ``bad-upload.json``, ``bad-sheet.json`` -- a table that is not an analysis sheet: kept, then
  the 422 ``bad_sheet`` answer of its check;
* ``bad-file.json`` -- the 400 ``bad_file`` answer for a file that is not ``.xlsx`` or ``.csv``.

Error files hold ``{"status": <code>, "body": <the server's JSON>}``.
"""

from __future__ import annotations

import argparse
import json
import os
import tempfile
import urllib.error
import urllib.request
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent


class Server:
    """The running app, with the dev launch key."""

    def __init__(self, port: int) -> None:
        self.origin = f"http://127.0.0.1:{port}"
        self.token = os.environ.get("QPILOT_APP_TOKEN", "qpilot-dev")

    def _send(self, path: str, data: bytes | None, content_type: str | None) -> tuple[int, object]:
        headers = {"x-qpilot-token": self.token, "origin": self.origin}
        if content_type:
            headers["content-type"] = content_type
        request = urllib.request.Request(
            self.origin + path,
            data=data,
            headers=headers,
            method="GET" if data is None else "POST",
        )
        try:
            with urllib.request.urlopen(request, timeout=300) as response:  # noqa: S310 (local)
                return response.status, json.loads(response.read())
        except urllib.error.HTTPError as err:
            return err.code, json.loads(err.read())

    def get(self, path: str) -> tuple[int, object]:
        """GET one API path."""
        return self._send(path, None, None)

    def post(self, path: str, body: object) -> tuple[int, object]:
        """POST a JSON body to one API path."""
        return self._send(path, json.dumps(body).encode(), "application/json")

    def upload(self, path: Path, name: str | None = None) -> tuple[int, object]:
        """``POST /api/sheets`` with the file in the multipart field ``sheet``."""
        boundary = uuid.uuid4().hex
        filename = name or path.name
        data = (
            (
                f"--{boundary}\r\n"
                f'Content-Disposition: form-data; name="sheet"; filename="{filename}"\r\n'
                "Content-Type: application/octet-stream\r\n\r\n"
            ).encode()
            + path.read_bytes()
            + f"\r\n--{boundary}--\r\n".encode()
        )
        return self._send("/api/sheets", data, f"multipart/form-data; boundary={boundary}")


def ok(answer: tuple[int, object]) -> object:
    """The body of a 200 answer (anything else stops the recording)."""
    status, body = answer
    assert status == 200, (status, body)
    return body


def sheets(folder: Path) -> dict[str, Path]:
    """The sheets to check, generated by the engine's test helpers."""
    from tests.engine.test_sheetcheck import (
        clean_columns,
        clean_sheet,
        fmt,
        synthetic,
        textbook,
        textbook_summaries,
        wide_table,
        write_csv,
    )

    out = {"clean": clean_sheet(folder)}

    study = synthetic()
    _, ddcq, _, _ = textbook(study, "MYC")
    columns = {**clean_columns(study), "Fold change MYC": 2.0**ddcq}
    header, rows = wide_table(study, columns, textbook_summaries(study))
    out["inverted"] = write_csv(folder / "inverted.csv", header, rows)

    dated = synthetic(targets=("MARCH1",))
    rows = []
    for i, (unit, group) in enumerate(zip(dated.units, dated.groups, strict=True)):
        for gene, shown in (("GAPDH", "GAPDH"), ("ACTB", "ACTB"), ("MARCH1", "1-Mar")):
            rows.append([unit, group, shown, fmt(dated.cq[gene][i], 2)])
    out["dates"] = write_csv(folder / "dates.csv", ["Sample", "Group", "Gene", "Cq"], rows)

    out["demo"] = demo_sheet(folder)

    bad = folder / "bad.csv"
    bad.write_text("nothing,to,see\n1,2,3\n", encoding="utf-8")
    out["bad"] = bad
    notes = folder / "notes.pdf"
    notes.write_bytes(b"%PDF-1.4\n")
    out["notes"] = notes
    return out


def demo_sheet(folder: Path) -> Path:
    """A clean wide sheet from the demo's own Cq values (as the engine's demo tests build it)."""
    from qpilot.io.datasets import VERMEULEN_FILENAME, default_cache_dir
    from qpilot.qpcr.curves import analyse_study
    from qpilot.qpcr.study import build_model
    from tests.engine.test_sheetcheck import (
        DEMO_GENES,
        DEMO_REFS,
        Study,
        demo_clean,
        demo_table,
        write_csv,
    )

    curves = analyse_study(default_cache_dir() / VERMEULEN_FILENAME)
    model = build_model(curves)
    unknown = curves[curves["sample_type"] == "unkn"]
    cq = unknown.pivot(index="sample", columns="target", values="cq")
    high, rest = sorted(model.high), sorted(model.rest)
    units = rest + high
    groups = ["rest"] * len(rest) + ["MYCN high"] * len(high)
    values = {g: cq.loc[units, g].to_numpy(dtype=float) for g in DEMO_REFS + DEMO_GENES}
    study = Study(units, groups, values, DEMO_REFS, "rest", DEMO_GENES)
    header, rows = demo_table(study, demo_clean(study))
    return write_csv(folder / "demo-sheet.csv", header, rows)


def write(name: str, data: object) -> None:
    """Write one answer next to this file."""
    (HERE / name).write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {name}")


def main() -> None:
    """Upload, check and record every answer the section's tests read."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--port", type=int, default=int(os.environ.get("APP_PORT", "7860")))
    parser.add_argument("--study", required=True, help="an analysed study id (12 hex)")
    args = parser.parse_args()
    server = Server(args.port)

    write("workspaces.json", ok(server.get("/api/workspaces")))
    with tempfile.TemporaryDirectory() as tmp:
        files = sheets(Path(tmp))

        clean = ok(server.upload(files["clean"]))
        assert isinstance(clean, dict)
        write("clean-upload.json", clean)
        url = f"/api/sheets/{clean['sheet_id']}/check"
        guessed = ok(server.post(url, {}))
        assert isinstance(guessed, dict)
        write("clean-guessed.json", guessed)
        # one column a person sets: the first fold-change column, taken as "not used"
        fc = next(c for c in guessed["mapping"]["columns"] if c["role"] == "fc")
        change = [{"column": fc["column"], "role": "ignored"}]
        write("clean-changed.json", ok(server.post(url, {"columns": change, "confirm": False})))
        write("clean-confirmed.json", ok(server.post(url, {"columns": change, "confirm": True})))

        for key in ("inverted", "dates"):
            up = ok(server.upload(files[key]))
            assert isinstance(up, dict)
            write(f"{key}-upload.json", up)
            write(f"{key}-guessed.json", ok(server.post(f"/api/sheets/{up['sheet_id']}/check", {})))

        demo = ok(server.upload(files["demo"]))
        assert isinstance(demo, dict)
        write("demo-upload.json", demo)
        write(
            "demo-study.json",
            ok(server.post(f"/api/sheets/{demo['sheet_id']}/check", {"study_id": args.study})),
        )

        bad = ok(server.upload(files["bad"]))
        assert isinstance(bad, dict)
        write("bad-upload.json", bad)
        status, body = server.post(f"/api/sheets/{bad['sheet_id']}/check", {})
        assert status == 422, (status, body)
        write("bad-sheet.json", {"status": status, "body": body})
        status, body = server.upload(files["notes"])
        assert status == 400, (status, body)
        write("bad-file.json", {"status": status, "body": body})


if __name__ == "__main__":
    main()
