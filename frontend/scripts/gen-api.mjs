// Generates src/api/schema.d.ts from the Python server's OpenAPI schema (no server needed).
// `--check` fails when the committed file differs (CI and tests/web/test_contract.py).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const out = resolve(here, "..", "src", "api", "schema.d.ts");
const venv = resolve(root, ".venv", "bin", "python");
const python = process.env.QPILOT_PYTHON ?? (existsSync(venv) ? venv : "python3");

const json = execFileSync(python, ["-m", "qpilot.web.openapi"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const ast = await openapiTS(JSON.parse(json), { alphabetize: true, exportType: true });
const text =
  "// Generated by `npm run gen:api` from qpilot/web (python -m qpilot.web.openapi). Do not edit.\n" +
  astToString(ast);

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== text) {
    console.error("src/api/schema.d.ts is out of date: run `npm run gen:api`.");
    process.exit(1);
  }
  console.log("src/api/schema.d.ts is up to date.");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
