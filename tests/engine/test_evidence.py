def test_every_item_has_present_absent_and_other_cases():
    """Coverage of the status per item across the cases above (one place to read it)."""
    seen = {item: set() for item in ITEMS}
    flags = {s: SampleFlags(integrity=True, lot=True, rt_batch=True) for s in ALL_SAMPLES}
    full = RdmlEvidence(runs=(RunFlags("e", "p0", True, True, True),), samples=flags)
    table = toy_table()
    nrt = table[table["sample"] == "u1a"].assign(sample="n", sample_type="nrt", well="P9")
    cases = [
        ledger(),
        ledger(doc=full),
        ledger(doc=no_flags(ALL_SAMPLES)),
        ledger(pd.concat([table, nrt], ignore_index=True)),
        ledger(toy_table(ntc=False), design=None, refs=("R1", "R2")),
        ledger(_spanning(toy_table(std=False), shared=True), design=None),
        ledger(_spanning(toy_table(std=False), shared=False), design=None),
        ledger(toy_table().assign(eff_indiv=float("nan"))),
    ]
    for led in cases:
        for item, status in led.statuses().items():
            seen[item].add(status)
    for item in ITEMS:
        if item == "rawness":  # always unknown until the raw-ness detector (add_plan 2.3)
            assert seen[item] == {"unknown"}
            continue
        assert {"present", "absent"} <= seen[item], item
    assert "not_applicable" in seen["inter_run_calibrator"]
    assert {"rna_integrity", "lots", "instrument"} <= {i for i in ITEMS if "unknown" in seen[i]}


